import { IArchitectWikiService } from '@shared/services';
import { registerSingleton, InstantiationType } from '@shared/instantiation/extensions';
import * as fs from 'fs';
import * as path from 'path';

export class ArchitectWikiService implements IArchitectWikiService {
  async analyzeCodebase(workspacePath: string): Promise<{ filesParsed: number; importsMap: Record<string, string[]> }> {
    const importsMap: Record<string, string[]> = {};
    let filesParsed = 0;

    const scanDir = (dir: string) => {
      if (!fs.existsSync(dir)) return;
      const entries = fs.readdirSync(dir, { withFileTypes: true });

      for (const entry of entries) {
        const fullPath = path.join(dir, entry.name);
        
        if (entry.isDirectory()) {
          if (['node_modules', '.git', 'dist', 'out', 'build', '.lumiq', 'temp_advanced_workspace', 'temp_advanced_user_data'].includes(entry.name)) {
            continue;
          }
          scanDir(fullPath);
          continue;
        }

        const ext = path.extname(entry.name).toLowerCase();
        if (['.ts', '.tsx', '.js', '.jsx'].includes(ext)) {
          filesParsed++;
          try {
            const content = fs.readFileSync(fullPath, 'utf8');
            const imports: string[] = [];
            
            const importRegex = /import\s+.*?\s+from\s+['"]([^'"]+)['"]/g;
            const requireRegex = /require\(\s*['"]([^'"]+)['"]\s*\)/g;
            
            let match;
            while ((match = importRegex.exec(content)) !== null) {
              imports.push(match[1]);
            }
            while ((match = requireRegex.exec(content)) !== null) {
              imports.push(match[1]);
            }

            const relativeFilePath = path.relative(workspacePath, fullPath).replace(/\\/g, '/');
            importsMap[relativeFilePath] = imports.filter(imp => imp.startsWith('.') || imp.startsWith('@shared/'));
          } catch {
            // ignore
          }
        }
      }
    };

    scanDir(workspacePath);
    return { filesParsed, importsMap };
  }

  async generateMermaidDiagram(workspacePath: string): Promise<string> {
    const { importsMap } = await this.analyzeCodebase(workspacePath);
    let diagram = 'graph TD\n';
    let relationsAdded = 0;

    for (const [file, imports] of Object.entries(importsMap)) {
      const fileId = this.sanitizeId(file);
      for (const imp of imports) {
        if (imp.startsWith('.')) {
          const resolvedRelPath = this.resolveImportFilePath(file, imp, workspacePath);
          const resolvedPath = resolvedRelPath || path.posix.join(path.posix.dirname(file), imp);
          const targetId = this.sanitizeId(resolvedPath);
          diagram += `  ${fileId}["${path.basename(file)}"] --> ${targetId}["${path.basename(resolvedPath)}"]\n`;
          relationsAdded++;
          
          if (relationsAdded > 30) {
            diagram += `  %% Limit reached (max 30 relations)\n`;
            return diagram;
          }
        }
      }
    }

    if (relationsAdded === 0) {
      diagram += `  A["Start"] --> B["No Local Dependencies Found"]\n`;
    }

    return diagram;
  }

  async writeWikiFile(workspacePath: string): Promise<string> {
    const { filesParsed, importsMap } = await this.analyzeCodebase(workspacePath);
    const diagram = await this.generateMermaidDiagram(workspacePath);

    let wiki = `# 🏛️ Codebase Architecture Wiki\n\n`;
    wiki += `Automatically generated by Lumiq Architect Wiki Service.\n\n`;
    wiki += `## 📊 Overview\n\n`;
    wiki += `- **Total Files Indexed**: ${filesParsed}\n`;
    wiki += `- **Architecture Layout**: Model-View-Controller / Service-Oriented Layered Architecture\n\n`;
    wiki += `## 🗺️ Module Dependency Diagram\n\n`;
    wiki += `\`\`\`mermaid\n${diagram}\`\`\`\n\n`;
    wiki += `## 📦 Core Modules Description\n\n`;
    wiki += `| File Path | Direct Local Imports | Description |\n`;
    wiki += `|-----------|----------------------|-------------|\n`;

    for (const [file, imports] of Object.entries(importsMap).slice(0, 15)) {
      wiki += `| \`${file}\` | ${imports.length} | Source component |\n`;
    }

    const wikiPath = path.join(workspacePath, 'ARCHITECTURE.md');
    fs.writeFileSync(wikiPath, wiki, 'utf8');
    return wikiPath;
  }

  private resolveImportFilePath(sourceFile: string, importPath: string, workspacePath: string): string | null {
    const sourceFullPath = path.join(workspacePath, sourceFile);
    const resolvedFullPathBase = path.resolve(path.dirname(sourceFullPath), importPath);

    const extensions = ['.ts', '.tsx', '.js', '.jsx'];
    for (const ext of extensions) {
      const fullPath = resolvedFullPathBase + ext;
      if (fs.existsSync(fullPath)) {
        return path.relative(workspacePath, fullPath).replace(/\\/g, '/');
      }
    }
    
    for (const ext of extensions) {
      const fullPath = path.join(resolvedFullPathBase, 'index' + ext);
      if (fs.existsSync(fullPath)) {
        return path.relative(workspacePath, fullPath).replace(/\\/g, '/');
      }
    }

    return null;
  }

  private sanitizeId(p: string): string {
    return p.replace(/[^a-zA-Z0-9]/g, '_');
  }
}

registerSingleton(IArchitectWikiService, ArchitectWikiService, InstantiationType.Delayed);
